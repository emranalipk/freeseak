#!/usr/bin/env node
/**
 * v1.0.3 — SEO mode gate (runs as part of `prebuild`, before `next build`).
 *
 * Writes public/_headers from the base template below:
 *   - SITE_MODE=production  → base only (no noindex anywhere)
 *   - anything else (default, fail-safe) → base + X-Robots-Tag noindex on /*,
 *     so the workers.dev deployment can never be indexed even if the meta
 *     tag were missed on some route.
 *
 * The edge Worker (src/worker.ts) enforces the same rule at runtime by host.
 * Launch day = set SITE_MODE=production in the Cloudflare Workers build
 * settings (docs/LAUNCH_CHECKLIST.md step 4) — no code change.
 *
 * Rule 3: the domain is read from src/lib/site.ts (regex), never hardcoded.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const siteTs = readFileSync(join(root, "src/lib/site.ts"), "utf8");
const m = siteTs.match(/export const SITE_URL\s*=\s*"(https:\/\/[^"]+)"/);
if (!m) {
  console.error("seo-mode: cannot find SITE_URL in src/lib/site.ts — refusing to write _headers");
  process.exit(1);
}
const SITE_URL = m[1];

const production = process.env.SITE_MODE === "production";

/* The base header set that shipped since v0.11.0 (security + caching). */
const BASE = `# FreeSeak asset headers (Cloudflare Workers static assets reads this file).
# Generated by scripts/seo-mode.mjs — edit the script, not this file.
# Security first: the site is fully static, client-side only.
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=()

# Hashed build output never changes for a given filename -> cache forever.
/_next/static/*
  Cache-Control: public, max-age=31536000, immutable

# Stable-named engine assets (pdf.js workers, cmaps + standard fonts,
# OCR WASM, fonts) are content-identical between deploys unless bumped
# by hand -> cache hard, revalidate daily.
/pdf.worker.min.mjs
  Cache-Control: public, max-age=86400
/pdf.renderer.min.mjs
  Cache-Control: public, max-age=86400
/pdfjs/*
  Cache-Control: public, max-age=86400
/ocr/*
  Cache-Control: public, max-age=86400
/fonts/*
  Cache-Control: public, max-age=86400

# Brand images have stable names but can be replaced on deploy -> revalidate.
/favicon.svg
  Cache-Control: public, max-age=86400
/favicon.ico
  Cache-Control: public, max-age=86400
/og-image.png
  Cache-Control: public, max-age=86400
/og/*
  Cache-Control: public, max-age=86400
/site.webmanifest
  Cache-Control: public, max-age=86400
`;

/* preview: hard noindex on every response, on top of the <meta> tag. */
const PREVIEW = `

# v1.0.3 SEO mode: PREVIEW — this deployment (workers.dev / preview host) is
# not launched. Every response is noindexed at the edge. Do not crawl-map it.
/*
  X-Robots-Tag: noindex, nofollow
`;

const out = production ? BASE : BASE + PREVIEW;
writeFileSync(join(root, "public/_headers"), out);

console.log(
  `seo-mode: SITE_MODE=${production ? "production" : "preview"} — public/_headers written` +
    (production ? ` (production: no noindex headers, sitemap ${SITE_URL}/sitemap.xml)` : " (preview: X-Robots-Tag noindex on /*)"),
);
